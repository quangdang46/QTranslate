"""Regression: the packaged bundle is a real, working app (Phase 8).

Phase 8's acceptance condition is *"a user installs the app, drops an
extension in, restarts, and it works with Python **not separately
installed**"*. That is a claim about an artifact, so it is tested against
an artifact rather than asserted.

This suite does NOT build (that takes ~40s and needs the network for the
uv tool). It verifies the two halves that make a build trustworthy:

  A. **The tool is honest.** `tools/build_bundle.py` must refuse to ship a
     bundle with a module gap: a qtranslate module present on disk but
     absent from the frozen TOCs. This is the check that catches the
     failure PyInstaller hides -- a lazy import nothing follows, which
     makes the app start and then die in front of the user.
  B. **The self-test actually fails.** `app._frozen_selftest` must report
     FAIL (not PASS, not an exception) when a dependency is missing. A
     green self-test that cannot go red is the known-answer-vector trap
     this project already hit three times, so it is pinned here.

  C. **The frozen gate list is exact.** The one module deliberately not
     frozen (`speech_input`, `dead:native-unavailable`) is named, and every
     other qtranslate module must be reachable.

Headless, no network, never runs a build.

Usage: python -I tests/regress_packaging.py
"""
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from qtranslate import app as _app  # noqa: E402

failures = []
n = [0]


def ck(name, cond, detail=""):
    n[0] += 1
    if not cond:
        failures.append("%s%s" % (name, (" -- " + detail) if detail else ""))


TOOL = "tools/build_bundle.py"
tool_src = io.open(TOOL, encoding="utf-8").read()

# --- A. the tool's own honesty ------------------------------------------

ck("build_bundle.py exists as the Phase 8 tool", len(tool_src) > 2000)

# The frozen-gap check is the thing that makes a build trustworthy, so it
# must exist and be wired into the build path (not written and forgotten).
ck("the tool checks the frozen module set against disk",
   "_frozen_gap" in tool_src)
ck("...and the build FAILS on a gap (returns 1)",
   "FROZEN-MODULE GAP" in tool_src and "return 1" in tool_src)

# The Python-version trap: `uv tool install pyinstaller` resolves its own
# Python, which lacks keyboard/pyperclip/Pillow -- the build then ships an
# app with no hotkeys and no icons. The tool must inject them explicitly.
ck("the tool injects the runtime deps into the build env",
   '--with", "pillow' in tool_src or '"--with", "pillow' in tool_src
   or "--with" in tool_src and "keyboard" in tool_src)
ck("...and the deps come from requirements.txt rather than being hardcoded",
   "requirements.txt" in tool_src)

# The spec must be generated (so the hook/exclude set is reviewable), and
# the placeholder substitution must be checked -- a silent miss here
# produces a FileNotFoundError nowhere near its cause.
ck("the spec is generated by the tool, not hand-maintained",
   "def write_spec" in tool_src)
ck("...and a missed substitution raises instead of writing a bad spec",
   "placeholders were not substituted" in tool_src)

# Verification runs the frozen EXE. A sys.path probe against `_internal`
# reports "missing" for a good bundle, because pure modules live inside
# the compressed PYZ -- so the check has to be the exe itself.
ck("verification runs the built executable itself",
   re.search(r'run\(\[exe,\s*"--selftest"\]', tool_src) is not None,
   "verify() must invoke the exe, not probe _internal")
ck("...and parses a machine marker from it",
   "SELFTEST " in tool_src)

# --- B. the selftest can actually go red -------------------------------


class _Boom:
    """A module object whose import always fails."""


def _run_selftest_without(*dep_names):
    """Run `_frozen_selftest` with named modules made unimportable."""
    import builtins
    real_import = builtins.__import__
    blocked = set(dep_names)

    def fake(name, *a, **k):
        if name in blocked or name.split(".")[0] in blocked:
            raise ImportError("blocked by regress_packaging: %s" % name)
        return real_import(name, *a, **k)

    buf = io.StringIO()
    builtins.__import__ = fake
    old = sys.stdout
    sys.stdout = buf
    try:
        rc = _app._frozen_selftest()
    finally:
        sys.stdout = old
        builtins.__import__ = real_import
    return rc, buf.getvalue()


rc_pass, out_pass = _run_selftest_without()
ck("the selftest passes as shipped", rc_pass == 0, out_pass[-300:])
ck("...and prints exactly one machine marker line",
   sum(1 for l in out_pass.split("\n") if l.startswith("SELFTEST ")) == 1)
ck("...and the marker says PASS", "SELFTEST PASS" in out_pass)

# This is the pin that matters: each of these must turn the marker red.
for dep in ("keyboard", "pyperclip", "PIL", "qtranslate.registry",
            "qtranslate.engine", "qtranslate.theme", "qtranslate.sdk",
            "qtranslate.tray_state", "qtranslate.ui_slots",
            "qtranslate.providers", "qtranslate.screens"):
    rc, out = _run_selftest_without(dep)
    ck("a missing %s turns the selftest FAIL" % dep,
       rc == 1 and "SELFTEST FAIL" in out,
       "rc=%s out=%r" % (rc, out[-200:]))

# And the FAIL line must name what is missing, or the build log is useless.
rc, out = _run_selftest_without("qtranslate.engine")
ck("a failure names the missing module",
   "qtranslate.engine" in out and "MISSING" in out, out[-300:])

# --- C. the deliberate exclusion is the ONLY one ----------------------
src = io.open("qtranslate/tray_state.py", encoding="utf-8").read()
ck("tray_state exists (it is frozen, so it must be on disk)",
   "def select_state" in src)
src2 = io.open("qtranslate/speech_input.py", encoding="utf-8").read()
ck("speech_input exists on disk but is deliberately NOT frozen",
   "speech_input" in tool_src and "NOT_FROZEN_OK" in tool_src)

# The tray-state divergence this pass fixed: app._sync_icon must use the
# native rule via tray_state, not an inlined hotkeys-based guess.
appsrc = io.open("qtranslate/app.py", encoding="utf-8").read()
ck("app._sync_icon resolves the icon through tray_state (the native rule)",
   "from qtranslate import tray_state as _TS" in appsrc
   and "_TS.select_state(" in appsrc,
   "the port must not inline a different 3-state rule than FUN_00418DA0")
ck("...and it feeds the mouse-arm flag and the hook-availability bit",
   "_TS.select_state(_mouse_mode[0], bool(_MOUSE_HOOK" in appsrc)
ck("the old hotkeys-based guess is gone",
   "any HotKey bound = on" not in appsrc)

# The ImportError this pass found: `from X import <submodule>` inside a
# try/except swallowed the failure and the D18 dialog never opened.
ck("the override dialog imports override_ui from its own module",
   re.search(r"from qtranslate\.extensions import \(\n"
             r"                ExtensionManager, write_saved_overrides\)\n"
             r"(?:            #[^\n]*\n)+"
             r"            from qtranslate import override_ui\n",
             appsrc) is not None,
   "importing a submodule from a package that does not export it is "
   "invisible to PyInstaller's Analysis AND fails at runtime")

# Prove the actual runtime behaviour, not just the source shape: importing
# the name app.py imports must succeed.
try:
    from qtranslate.extensions import (ExtensionManager,  # noqa: F401
                                       write_saved_overrides)
    from qtranslate import override_ui as _ov
    ck("app.py's override imports resolve for real",
       callable(_ov.pick_override_winners)
       and callable(write_saved_overrides))
except Exception as exc:
    ck("app.py's override imports resolve for real", False, repr(exc))

# --- packaging artefacts ------------------------------------------------
# A built tree is evidence, not a requirement of this suite -- but if one
# is present it must be complete, so a stale/partial dist is not mistaken
# for a working bundle.
DIST = os.path.join("dist", "QTranslate")
if os.path.isdir(DIST):
    ck("the built tree has the exe",
       os.path.exists(os.path.join(DIST, "QTranslate.exe")))
    ck("...and the frozen runtime root",
       os.path.isdir(os.path.join(DIST, "_internal")))
    ck("...and the frozen stdlib",
       os.path.exists(os.path.join(DIST, "_internal", "base_library.zip")))
    ck("...and Pillow is inside the bundle (not a system install)",
       os.path.isdir(os.path.join(DIST, "_internal", "PIL")))
    # `keyboard`/`pyperclip` are pure modules -> they live in the PYZ, so
    # their presence is proven by the exe's --selftest rather than here.
else:
    print("NOTE: no dist/QTranslate tree -- build with "
          "`python -I tools/build_bundle.py` to exercise the artifact "
          "checks (the build itself needs the network).")

# The ICU of the whole suite: `--selftest` must not be swallowed by the
# CLI parser, which would make the packaged build unverifiable.
ck("main() routes --selftest before any UI/config work",
   re.search(r"def main\(\):\n(?:    #[^\n]*\n)*"
             r'    if "--selftest" in sys\.argv\[1:\]:\n'
             r"        return _frozen_selftest\(\)",
             appsrc) is not None,
   "the flag must be handled before _seed_service_options / Tk")

if failures:
    print("FAIL %d/%d" % (len(failures), n[0]))
    for f in failures:
        print("  -", f)
    raise SystemExit(1)
print("regress_packaging: all checks ok (%d assertions)" % n[0])
