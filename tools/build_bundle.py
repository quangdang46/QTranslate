def spec_path():
    return os.path.join(HERE, "qtranslate.spec")


# Where the native install lives and the icon the bundle ships. The port
# already reads Services/<Name>/Service.ico from the installed native copy
# at runtime; the bundle needs its own icon, so the Google Translate
# service icon — the default service, and a real asset from the shipped
# product rather than a generated placeholder — is copied out and frozen.
INSTALL_DIR = os.environ.get("QTRANSLATE_DIR",
                             r"C:\Program Files (x86)\QTranslate")
ICON_SRC = os.path.join(INSTALL_DIR, "Services", "Google Translate",
                        "Service.ico")
BUILD_ASSETS = os.path.join(HERE, "build", "assets")


def _quad(v: str) -> tuple:
    """`a.b.c` -> `(a, b, c, 0)`, the 4-part tuple Win32 wants."""
    parts = [int(p) for p in v.split(".") if p.strip().isdigit()]
    while len(parts) < 3:
        parts.append(0)
    return tuple(parts[:3]) + (0,)


def prepare_assets() -> dict:
    """Materialize the exe icon + version resource the spec references.

    The spec names `build/assets/QTranslate.ico` and
    `build/assets/version_info.txt`. Writing them here (rather than
    committing a binary blob) keeps the provenance checkable: the icon is
    copied from the installed native copy when present, and the version
    info is generated from the constants above.

    Returns {"icon": path_or_None, "version": path}.
    """
    os.makedirs(BUILD_ASSETS, exist_ok=True)
    icon = os.path.join(BUILD_ASSETS, EXE_NAME + ".ico")
    if os.path.exists(ICON_SRC):
        # Re-encode to the sizes the shell wants (16/24/32/48/256) so a
        # single 16x16 frame does not become an ugly scaled tile.
        try:
            from PIL import Image
            im = Image.open(ICON_SRC).convert("RGBA")
            frames = [im.resize((s, s), Image.LANCZOS)
                      for s in (16, 24, 32, 48, 256)]
            frames[0].save(icon, format="ICO",
                           sizes=[f.size for f in frames],
                           append_images=frames[1:])
        except Exception as exc:            # Pillow absent or odd file
            print("icon re-encode failed (%s); copying verbatim" % exc)
            import shutil
            shutil.copyfile(ICON_SRC, icon)
    else:
        # Fall back to the native's OWN application icon, recovered from the
        # EXE's RT_ICON resources (group 0) and committed under
        # qtranslate/assets/app_icon/. It matches the native window's title
        # bar icon pixel for pixel (ssd 144 over 768 channel bytes).
        recovered = os.path.join(HERE, "qtranslate", "assets", "app_icon")
        recovered_ico = os.path.join(recovered, "QTranslate.ico")
        if os.path.isfile(recovered_ico):
            # The recovered .ico already carries native's own frames
            # (256/48/32/16), so it is copied verbatim -- no re-encode, and
            # no Pillow needed (the build runs with -I, which hides it).
            import shutil
            shutil.copyfile(recovered_ico, icon)
            print("app icon: recovered from the EXE's RT_ICON resources")
        else:
            print("NOTE: native Service.ico not found at %s and no recovered "
                  "app icon -- the exe ships without an icon" % ICON_SRC)
            icon = None

    version = os.path.join(BUILD_ASSETS, "version_info.txt")
    # `ffi` fields are the only numbers the resource compiler reads; every
    # version-looking string below is derived from the constants so the exe
    # metadata cannot drift from BUNDLE_VERSION/APP_VERSION.
    file_q, prod_q = _quad(BUNDLE_VERSION), _quad(APP_VERSION)
    with open(version, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(VERSION_INFO % {
            "filevers": ", ".join(str(x) for x in file_q),
            "prodvers": ", ".join(str(x) for x in prod_q),
            "file_version": BUNDLE_VERSION,
            "product_version": APP_VERSION,
            "app_version": APP_VERSION,
        })
    return {"icon": icon, "version": version}


