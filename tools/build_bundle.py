def write_spec() -> str:
    assets = prepare_assets()
    spec = SPEC
    # The spec is written with placeholder basenames and the real (build/)
    # paths substituted here, so the committed spec stays a readable
    # template. A placeholder left behind would be a confusing build error
    # far from its cause, so the substitution is checked.
    v_repr = repr(assets["version"])
    spec = spec.replace("'version_info.txt'", v_repr)
    if assets["icon"]:
        spec = spec.replace("'QTranslate.ico'", repr(assets["icon"]))
    # Both placeholders must be gone. An icon-less build is legitimate
    # (native icon not installed), so only the version path is mandatory.
    leftovers = [tok for tok in ("'version_info.txt'",)
                 if tok in spec]
    if assets["icon"]:
        leftovers += [tok for tok in ("'QTranslate.ico'",) if tok in spec]
    if leftovers or v_repr not in spec:
        raise AssertionError(
            "spec placeholders were not substituted (%r): the template text "
            "and the substitution in tools/build_bundle.py have drifted. Fix "
            "the tool, not the spec." % (leftovers,))
    with open(spec_path(), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(spec)
    return spec_path()


def run(cmd, **kw) -> subprocess.CompletedProcess:
    print("$ " + " ".join(cmd))
    return subprocess.run(cmd, cwd=HERE, **kw)


def _pyinstaller_argv():
    """How to invoke PyInstaller so the bundle has the RIGHT Python.

    This repo's Python is uv-managed and PEP-668 locked, so PyInstaller is
    installed as a uv *tool* rather than into the interpreter. Two traps:

      1. `uv tool install pyinstaller` resolves its **own** Python (3.13),
         which lacks this project's deps (`keyboard`, `pyperclip`,
         `Pillow`) — the build silently drops them and the shipped app
         starts with no hotkeys and no icons.
      2. `uv tool run` is **isolated**, so even matching the Python version
         with `--python 3.12` hides the deps that live in the *repo
         interpreter's* site-packages.

    So the deps are injected into the tool environment with `--with`, using
    the exact spec strings from `requirements.txt`. The frozen module set
    is then checked against the bundled TOCs (`_frozen_gap`) — a missing
    dep is a build failure, not a warning.
    """
    try:
        import PyInstaller.__main__  # noqa: F401
        return [sys.executable, "-I", "-m", "PyInstaller"], None
    except ImportError:
        pass
    want = "%d.%d" % sys.version_info[:2]
    # The deps that MUST be in the bundle. pyperclip ships on every platform;
    # keyboard is Windows-only (it aborts the process on macOS Cocoa), so it
    # is only bundled on Windows. Pillow ships on every platform (service
    # strip, tray glyphs, OCR region capture). The optional ones (pystray,
    # comtypes, playwright) are deliberately absent -- the app explains each
    # when it is missing.
    deps = ["--with", "pillow", "--with", "pyperclip"]
    if sys.platform == "win32":
        deps.append("--with keyboard==0.13.5")
    req = os.path.join(HERE, "requirements.txt")
    if os.path.exists(req):
        for line in open(req, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "==" in line:
                mod = line.split("==")[0].strip()
                if mod == "pyperclip":
                    # already injected above with the exact version
                    pass
                elif mod == "keyboard" and sys.platform == "win32":
                    # already injected above
                    pass
    argv = ["uv", "tool", "run", "--python", want]
    argv += deps
    argv += ["--from", "pyinstaller", "pyinstaller"]
    return argv, None


def build() -> int:
    write_spec()
    launcher, pyver = _pyinstaller_argv()
    if not launcher:
        print("pyinstaller not available to this interpreter.")
        print("Install with:  uv tool install pyinstaller")
        print("or:            %s -m pip install pyinstaller"
              % os.path.basename(sys.executable))
        return 3
    want = "%d.%d" % sys.version_info[:2]
    if pyver is not None and pyver != tuple(sys.version_info[:2]):
        print("WARNING: building under Python %s while the repo runs %s -- "
              "bundled deps may not resolve" % (pyver, want))
    print("using:", launcher[0], "(Python %s)" % want)
    rc = run(launcher +
             ["--noconfirm", "--clean", "--distpath",
              os.path.join(HERE, "dist"), "--workpath",
              os.path.join(HERE, "build", "pyinstaller"),
              os.path.join(HERE, "qtranslate.spec")]).returncode
    if rc:
        print("PyInstaller failed")
        return rc
    # The frozen module set is the thing that breaks silently, so it is
    # checked from the Analysis TOC rather than trusted.
    missing = _frozen_gap(os.path.join(HERE, "build", "pyinstaller"))
    if missing:
        print("FROZEN-MODULE GAP (these exist on disk but were not bundled):")
        for m, why in missing:
            print("  - %s (%s)" % (m, why))
        print("Add them to the spec's hiddenimports, or fix the import that "
              "hides them from Analysis.")
        return 1
    return verify(os.path.join(HERE, "dist", EXE_NAME))


def _frozen_gap(workpath: str):
    """qtranslate modules present on disk but absent from the frozen set.

    Analysis follows real imports; a module reached only by `__main__`, by a
    `from pkg import <submodule>` PyInstaller cannot resolve, or simply
    orphaned, is missing from the bundle and fails at runtime. This reads
    the Analysis/PYZ TOCs, so it sees what was ACTUALLY frozen.

    Returns a list of ``(module, why)`` for every disk module absent from
    the bundle, EXCEPT those in NOT_FROZEN_OK, whose absence is a recorded
    decision: a module nothing imports is dead weight in a shipped
    installer, and the point of the check is to be told about a NEW orphan
    rather than to re-litigate an old one.
    """
    # Deliberately not frozen, with the reason. `speech_input` ports native's
    # full-duplex speech URL builder, whose live path is dead
    # (native-unavailable) and whose capture path was never implemented --
    # it exists for RE completeness, not for the shipped app.
    NOT_FROZEN_OK = {
        "qtranslate.speech_input":
            "native-unavailable: the live speech path is retired and the "
            "capture path is unimplemented; RE-completeness only",
    }
    toc_dir = os.path.join(workpath, "qtranslate")
    frozen = set()
    # BOTH front ends are read: the spec has two Analysis objects, and
    # each writes its own numbered TOC.
    for name in ("Analysis-00.toc", "Analysis-01.toc",
                 "PYZ-00.toc", "PYZ-01.toc"):
        p = os.path.join(toc_dir, name)
        if not os.path.exists(p):
            continue
        text = open(p, encoding="utf-8", errors="replace").read()
        frozen.update(re.findall(r"\('(qtranslate(?:\.[A-Za-z0-9_]+)*)'", text))
    on_disk = set()
    for sub in ("qtranslate", "qtranslate/services", "qtranslate/providers",
                "qtranslate/qt"):
        if not os.path.isdir(sub):
            continue
        for f in os.listdir(sub):
            if not f.endswith(".py"):
                continue
            mod = sub.replace("/", ".")
            on_disk.add(mod if f == "__init__.py"
                        else mod + "." + f[:-3])
    gap = sorted(on_disk - frozen - set(NOT_FROZEN_OK))
    return [(m, "not reached by any import Analysis followed")
            for m in gap]


def verify(dist_dir: str) -> int:
    """Prove the built tree is a working app, without opening a window.

    Two checks, each of which a broken bundle fails:

      1. The expected files exist (exe + `_internal` runtime root + the
         frozen stdlib).
      2. **The frozen executable itself** runs `main()`'s `--selftest`
         branch and reports its import graph intact. This is the only test
         that can see a module PyInstaller's Analysis never followed: the
         app would otherwise start for the user, hit a lazy `import`, and
         die. Importing from `_internal` directly is NOT equivalent — the
         pure modules live inside the compressed PYZ, so a sys.path probe
         reports "missing" for a perfectly good bundle.

    No window is opened: `--selftest` returns before any Tk call.
    """
    import json

    problems = []
    exe = os.path.join(dist_dir, EXE_NAME + ".exe")
    internal = os.path.join(dist_dir, "_internal")

    for p, why in ((exe, "the entry-point executable"),
                   (internal, "the bundled runtime root"),
                   (os.path.join(internal, "base_library.zip"),
                    "the frozen stdlib")):
        if not os.path.exists(p):
            problems.append(f"missing {why}: {p}")
    if problems:
        for p in problems:
            print("  -", p)
        return 1

    # 2: run the real exe with the selftest flag.
    proc = run([exe, "--selftest"], capture_output=True, timeout=180)
    out = (proc.stdout or b"").decode("utf-8", "replace")
    err = (proc.stderr or b"").decode("utf-8", "replace")
    print(out.rstrip())
    if err.strip():
        print("stderr:", err.strip()[-1500:])
    marker = next((l for l in out.split("\n") if l.startswith("SELFTEST ")),
                  None)
    if marker is None:
        problems.append("the frozen exe produced no SELFTEST marker "
                        "(rc=%s) -- it did not reach the selftest branch"
                        % proc.returncode)
    elif "FAIL" in marker:
        problems.append("frozen selftest failed: %s" % marker.strip())
    if proc.returncode != 0 and not problems:
        problems.append("frozen exe exited %s without a failing selftest"
                        % proc.returncode)

    if problems:
        print("VERIFY FAILED:")
        for p in problems:
            print("  -", p)
        return 1
    return 0
    print("verify: the bundle imports and resolves providers from "
          "_internal with the repo off sys.path")
    return 0


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", action="store_true",
                    help="write the spec only, do not build")
    ap.add_argument("--verify-only", metavar="DIST_DIR",
                    help="verify an existing dist tree")
    a = ap.parse_args(argv)
    if a.verify_only:
        return verify(a.verify_only)
    if a.spec:
        print("wrote", write_spec())
        return 0
    return build()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
